import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, "..");

process.chdir(rootDir);

const configModule = await import("../sd.config.ts");
const lightConfig = configModule.default;
const darkConfig = configModule.darkConfig;

console.log("Building light theme tokens...");
const sdLight = new StyleDictionary(lightConfig);
await sdLight.buildAllPlatforms();

console.log("Building dark theme tokens...");
const sdDark = new StyleDictionary(darkConfig);
await sdDark.buildAllPlatforms();

console.log("Combining into tokens.css...");
const buildDir = resolve(rootDir, "build/css");

const primitivesCSS = readFileSync(
  resolve(buildDir, "primitives.css"),
  "utf-8",
);
const lightCSS = readFileSync(resolve(buildDir, "semantic-light.css"), "utf-8");
const darkCSS = readFileSync(resolve(buildDir, "semantic-dark.css"), "utf-8");

const combinedCSS = `/* Auto-generated by Style Dictionary — do not edit manually */

/* Primitive tokens */
${primitivesCSS}
/* Semantic tokens (light) */
${lightCSS}
/* Semantic tokens (dark) */
${darkCSS}`;

writeFileSync(resolve(buildDir, "tokens.css"), combinedCSS);

console.log("Build complete:");
console.log(
  "  → build/css/tokens.css       (web, via @import in services/web/src/index.css)",
);
console.log("  → build/json/resolved.json   (AI context)");
console.log(
  "  → build/ts/light.ts          (mobile NativeWind, via services/mobile/tailwind.config.ts)",
);
console.log(
  "  → build/ts/dark.ts           (dark theme — wire to mobile when dark mode is added)",
);
